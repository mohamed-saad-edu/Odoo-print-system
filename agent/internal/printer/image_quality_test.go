package printer

// WP7 receipt image-quality suite.
//
// Fixtures:
//   - A procedural anti-aliased fixture: built at 4x, box-averaged to
//     576px (the 80mm @ 203dpi class), so edges carry true fractional
//     coverage like browser-rasterized text. It contains a QR-like grid
//     with fractional 7.5px modules, barcode bars of 1..4px, 1px/2px
//     lines, 1px dots and a diagonal — the stroke/bar/module geometry
//     a thermal receipt must preserve.
//   - testdata/wp7_receipt_576.png: a real-content receipt (shaped
//     Arabic with ligatures/diacritics via PIL+raqm+Noto Naskh, English,
//     digits, a real QR code and a real Code128 barcode) generated by
//     testdata/wp7_generate_fixture.py. QR/barcode decodability of the
//     rendered outputs is verified by the WP7 Python check (zxing-cpp);
//     this Go suite verifies dimensions, geometry and byte-integrity,
//     which are the properties a Go test can prove without a decoder
//     dependency.
//
// Environment dump: setting WP7_QUALITY_DUMP_DIR writes rendered bitmap
// PNGs and PDFs there for the external decode check. Unset by default.

import (
	"bytes"
	"encoding/binary"
	"image"
	"image/color"
	"image/jpeg"
	"image/png"
	"math"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
)

// --- procedural anti-aliased fixture -------------------------------------

type wp7ProcFixture struct {
	aa    *image.Gray // anti-aliased source, 576x900
	ideal *image.Gray // bilevel ground truth: coverage >= 50% counts as ink
	mods  [25][25]bool
	bars  []int // barcode bar widths in target pixels, alternating from black
}

func wp7BuildProcFixture() wp7ProcFixture {
	const S = 4
	W, H := 576*S, 900*S
	hi := image.NewGray(image.Rect(0, 0, W, H))
	for i := range hi.Pix {
		hi.Pix[i] = 255
	}
	set := func(x, y, w, h int) {
		for yy := y; yy < y+h && yy < H; yy++ {
			for xx := x; xx < x+w && xx < W; xx++ {
				hi.Pix[yy*W+xx] = 0
			}
		}
	}
	var f wp7ProcFixture
	seed := uint32(999)
	next := func() bool { seed = seed*1103515245 + 12345; return seed>>16&1 == 1 }
	for r := 0; r < 25; r++ {
		for c := 0; c < 25; c++ {
			inFinder := (r < 7 && c < 7) || (r < 7 && c >= 18) || (r >= 18 && c < 7)
			var b bool
			if inFinder {
				fr, fc := r, c
				if r < 7 && c >= 18 {
					fc = c - 18
				} else if r >= 18 {
					fr = r - 18
				}
				b = fr == 0 || fr == 6 || fc == 0 || fc == 6 || (fr >= 2 && fr <= 4 && fc >= 2 && fc <= 4)
			} else if r == 6 || c == 6 {
				b = (r+c)%2 == 0
			} else {
				b = next()
			}
			f.mods[r][c] = b
			if b {
				set(64+c*30+2, 64+r*30+2, 30, 30)
			}
		}
	}
	f.bars = []int{1, 2, 1, 3, 2, 4, 1, 1, 3, 2, 1, 4, 2, 1, 3, 1}
	x := 64
	black := true
	for _, bw := range f.bars {
		if black {
			set(x+2, 1100, bw*S, 240)
		}
		x += bw * S
		black = !black
	}
	for i := 0; i < 400; i++ {
		set(64+i*4, 1500+i*2, 6, 6)
	}
	for i := 0; i < 10; i++ {
		set(64, 2000+i*48, 800, 4)
		set(64, 2020+i*48, 800, 8)
	}
	for r := 0; r < 4; r++ {
		for c := 0; c < 12; c++ {
			set(64+c*64, 2600+r*64, 4, 4)
			set(64+c*64+1600, 2600+r*64, 6, 6)
		}
	}
	f.aa = image.NewGray(image.Rect(0, 0, 576, 900))
	f.ideal = image.NewGray(image.Rect(0, 0, 576, 900))
	for y := 0; y < 900; y++ {
		for xx := 0; xx < 576; xx++ {
			sum := 0
			for dy := 0; dy < S; dy++ {
				for dx := 0; dx < S; dx++ {
					sum += int(hi.Pix[(y*S+dy)*W+xx*S+dx])
				}
			}
			v := uint8(sum / (S * S))
			f.aa.Pix[y*576+xx] = v
			if v < 128 {
				f.ideal.Pix[y*576+xx] = 0
			} else {
				f.ideal.Pix[y*576+xx] = 255
			}
		}
	}
	return f
}

func wp7EncodeGrayJPEG(g *image.Gray, quality int) []byte {
	rgba := image.NewRGBA(g.Bounds())
	for y := 0; y < g.Bounds().Dy(); y++ {
		for x := 0; x < g.Bounds().Dx(); x++ {
			v := g.GrayAt(x, y).Y
			rgba.Set(x, y, color.RGBA{R: v, G: v, B: v, A: 255})
		}
	}
	var buf bytes.Buffer
	if err := jpeg.Encode(&buf, rgba, &jpeg.Options{Quality: quality}); err != nil {
		panic(err)
	}
	return buf.Bytes()
}

// wp7DecodeESCPOS parses GS v 0 bands back into a bilevel bitmap.
func wp7DecodeESCPOS(t *testing.T, out []byte) ([][]bool, int, int) {
	t.Helper()
	if len(out) < 2 || out[0] != 0x1b || out[1] != 0x40 {
		t.Fatal("ESC/POS output lacks the ESC @ initialize prefix")
	}
	off := 2
	var rows [][]bool
	w := 0
	for off+8 <= len(out) {
		if !bytes.Equal(out[off:off+4], []byte{0x1d, 0x76, 0x30, 0}) {
			t.Fatalf("ESC/POS output changed GS v 0 framing at offset %d", off)
		}
		rowBytes := int(binary.LittleEndian.Uint16(out[off+4:]))
		bh := int(binary.LittleEndian.Uint16(out[off+6:]))
		if bh < 1 || bh > 256 || off+8+rowBytes*bh > len(out) {
			t.Fatal("ESC/POS band dimensions changed")
		}
		off += 8
		w = rowBytes * 8
		for y := 0; y < bh; y++ {
			row := make([]bool, w)
			for x := 0; x < w; x++ {
				row[x] = out[off+y*rowBytes+x/8]&(0x80>>uint(x%8)) != 0
			}
			rows = append(rows, row)
		}
		off += rowBytes * bh
	}
	if off != len(out) {
		t.Fatalf("ESC/POS output has %d trailing bytes", len(out)-off)
	}
	return rows, w, len(rows)
}

func wp7Disagreements(rows [][]bool, ideal *image.Gray) int {
	bad := 0
	for y := 0; y < ideal.Bounds().Dy(); y++ {
		for x := 0; x < ideal.Bounds().Dx(); x++ {
			if rows[y][x] != (ideal.GrayAt(x, y).Y < 128) {
				bad++
			}
		}
	}
	return bad
}

func wp7Dump(t *testing.T, name string, rows [][]bool) {
	t.Helper()
	dir := os.Getenv("WP7_QUALITY_DUMP_DIR")
	if dir == "" {
		return
	}
	h := len(rows)
	w := 0
	if h > 0 {
		w = len(rows[0])
	}
	img := image.NewGray(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			if rows[y][x] {
				img.Pix[y*w+x] = 0
			} else {
				img.Pix[y*w+x] = 255
			}
		}
	}
	f, err := os.Create(filepath.Join(dir, name))
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	if err := png.Encode(f, img); err != nil {
		t.Fatal(err)
	}
}

func wp7DumpBytes(t *testing.T, name string, data []byte) {
	t.Helper()
	dir := os.Getenv("WP7_QUALITY_DUMP_DIR")
	if dir == "" {
		return
	}
	if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil {
		t.Fatal(err)
	}
}

// Pre-WP7 point-sampling resampler, kept in-test only as the old algorithm
// for the before/after comparison. Production code no longer uses it.
func wp7ResizeNearestReference(src image.Image, width int) image.Image {
	sw, sh := src.Bounds().Dx(), src.Bounds().Dy()
	h := max(1, int(math.Round(float64(sh)*float64(width)/float64(sw))))
	dst := image.NewRGBA(image.Rect(0, 0, width, h))
	for y := 0; y < h; y++ {
		sy := src.Bounds().Min.Y + y*sh/h
		for x := 0; x < width; x++ {
			sx := src.Bounds().Min.X + x*sw/width
			dst.Set(x, y, src.At(sx, sy))
		}
	}
	return dst
}

func wp7ThresholdBitmap(g *image.Gray, threshold uint8) [][]bool {
	h, w := g.Bounds().Dy(), g.Bounds().Dx()
	rows := make([][]bool, h)
	for y := 0; y < h; y++ {
		rows[y] = make([]bool, w)
		for x := 0; x < w; x++ {
			rows[y][x] = g.GrayAt(x, y).Y < threshold
		}
	}
	return rows
}


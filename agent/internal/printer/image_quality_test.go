func TestWP7QualityProceduralGeometry(t *testing.T) {
	f := wp7BuildProcFixture()
	for _, q := range []int{90, 95} {
		out, err := JPEGToESCPOSWithMaxWidth(wp7EncodeGrayJPEG(f.aa, q), 256, 576)
		if err != nil {
			t.Fatal(err)
		}
		rows, w, h := wp7DecodeESCPOS(t, out)
		if w < 576 || h != 900 {
			t.Fatalf("q=%d: dimensions changed to %dx%d, want 576 wide x 900", q, w, h)
		}
		// Right-edge padding bits beyond 576 must stay white: 576 is a
		// multiple of 8, so rowBytes must be exactly 72.
		if w != 576 {
			t.Fatalf("q=%d: row width %d, want exactly 576", q, w)
		}
		bad := wp7Disagreements(rows, f.ideal)
		// Locks the fixed-180 threshold decision: Otsu measured 3338 and
		// Floyd-Steinberg ~5481 disagreements on this fixture class at
		// q90; the production threshold must stay far below both.
		if bad > 100 {
			t.Fatalf("q=%d: %d disagreements vs ideal, want <=100", q, bad)
		}
		// QR-like module geometry: majority vote over each module's
		// central 5x5 (grid origin 16.5px, pitch 7.5px, fractional).
		for r := 0; r < 25; r++ {
			for c := 0; c < 25; c++ {
				cx := int(16.5 + float64(c)*7.5 + 3)
				cy := int(16.5 + float64(r)*7.5 + 3)
				black := 0
				for yy := cy - 2; yy <= cy+2; yy++ {
					for xx := cx - 2; xx <= cx+2; xx++ {
						if rows[yy][xx] {
							black++
						}
					}
				}
				if (black >= 13) != f.mods[r][c] {
					t.Fatalf("q=%d: QR module (%d,%d) flipped", q, r, c)
				}
			}
		}
		// Barcode bar geometry on the band's centre row, measured against
		// the ideal raster's own runs (not nominal widths: a 1px bar at a
		// half-pixel offset legitimately renders 2px wide in both).
		// Exact run count, each run within 1px: no merged or dropped bars.
		extractRuns := func(get func(x int) bool) []int {
			var runs []int
			cur, n := get(16), 0
			for x := 16; x < 16+120; x++ {
				if get(x) == cur {
					n++
				} else {
					runs = append(runs, n)
					cur, n = get(x), 1
				}
			}
			return append(runs, n)
		}
		runs := extractRuns(func(x int) bool { return rows[300][x] })
		wantRuns := extractRuns(func(x int) bool { return f.ideal.GrayAt(x, 300).Y < 128 })
		if len(runs) != len(wantRuns) {
			t.Fatalf("q=%d: barcode runs %d, want %d (%v vs %v)", q, len(runs), len(wantRuns), runs, wantRuns)
		}
		for i, want := range wantRuns {
			if runs[i] < want-1 || runs[i] > want+1 {
				t.Fatalf("q=%d: barcode run %d width %d, want %d±1", q, i, runs[i], want)
			}
		}
		wp7Dump(t, "wp7_procedural_escpos_q"+strconv.Itoa(q)+".png", rows)
	}
}

func TestWP7QualityAreaDownscaleBeatsNearest(t *testing.T) {
	f := wp7BuildProcFixture()
	// Non-integral downscale: 1000x1563 (nearest-upscaled source) -> 576.
	wide := image.NewRGBA(image.Rect(0, 0, 1000, 1563))
	for y := 0; y < 1563; y++ {
		for x := 0; x < 1000; x++ {
			v := f.aa.GrayAt(x*576/1000, y*900/1563).Y
			wide.Set(x, y, color.RGBA{R: v, G: v, B: v, A: 255})
		}
	}
	var enc bytes.Buffer
	if err := jpeg.Encode(&enc, wide, &jpeg.Options{Quality: 90}); err != nil {
		t.Fatal(err)
	}
	out, err := JPEGToESCPOSWithMaxWidth(enc.Bytes(), 256, 576)
	if err != nil {
		t.Fatal(err)
	}
	rows, w, h := wp7DecodeESCPOS(t, out)
	if w != 576 || h != 900 {
		t.Fatalf("downscaled dimensions %dx%d, want 576x900", w, h)
	}
	newBad := wp7Disagreements(rows, f.ideal)
	// Old algorithm on the same input, through the same threshold.
	dec, err := jpeg.Decode(bytes.NewReader(enc.Bytes()))
	if err != nil {
		t.Fatal(err)
	}
	near := wp7ResizeNearestReference(dec, 576)
	ng := image.NewGray(near.Bounds())
	for y := 0; y < near.Bounds().Dy() && y < 900; y++ {
		for x := 0; x < 576; x++ {
			ng.SetGray(x, y, color.Gray{Y: grayscale(near.At(x, y))})
		}
	}
	oldBad := 0
	oldRows := wp7ThresholdBitmap(ng, 180)
	for y := 0; y < 900; y++ {
		for x := 0; x < 576; x++ {
			if oldRows[y][x] != (f.ideal.GrayAt(x, y).Y < 128) {
				oldBad++
			}
		}
	}
	// Measured at introduction: 4142 (area) vs 18293 (nearest). Require
	// at least a 2x improvement so the test survives encoder variance.
	if newBad*2 >= oldBad {
		t.Fatalf("area downscale %d disagreements, nearest %d: want area < half of nearest", newBad, oldBad)
	}
	wp7Dump(t, "wp7_downscaled_escpos.png", rows)
}

func TestWP7QualityRealReceipt(t *testing.T) {
	raw, err := os.ReadFile("testdata/wp7_receipt_576.png")
	if err != nil {
		t.Fatal(err)
	}
	src, err := png.Decode(bytes.NewReader(raw))
	if err != nil {
		t.Fatal(err)
	}
	if src.Bounds().Dx() != 576 {
		t.Fatalf("fixture width %d, want 576", src.Bounds().Dx())
	}
	h := src.Bounds().Dy()
	// Source ink bounding box at 50% coverage.
	srcGray := image.NewGray(src.Bounds())
	for y := 0; y < h; y++ {
		for x := 0; x < 576; x++ {
			srcGray.SetGray(x, y, color.Gray{Y: grayscale(src.At(x, y))})
		}
	}
	bbox := func(g *image.Gray, thr uint8) (x0, y0, x1, y1 int) {
		x0, y0, x1, y1 = 576, h, -1, -1
		for y := 0; y < h; y++ {
			for x := 0; x < 576; x++ {
				if g.GrayAt(x, y).Y < thr {
					x0, y0 = min(x0, x), min(y0, y)
					x1, y1 = max(x1, x), max(y1, y)
				}
			}
		}
		return x0, y0, x1, y1
	}
	sx0, sy0, sx1, sy1 := bbox(srcGray, 128)
	for _, q := range []int{90, 95} {
		out, err := JPEGToESCPOSWithMaxWidth(wp7EncodeGrayJPEG(srcGray, q), 256, 576)
		if err != nil {
			t.Fatal(err)
		}
		rows, w, rh := wp7DecodeESCPOS(t, out)
		if w != 576 || rh != h {
			t.Fatalf("q=%d: real receipt became %dx%d, want 576x%d (no crop, no rescale)", q, w, rh, h)
		}
		// No clipping: rendered ink box must match the source ink box
		// within 1px on every side (threshold 180 keeps >=30% coverage).
		rx0, ry0, rx1, ry1 := 576, h, -1, -1
		for y := 0; y < rh; y++ {
			for x := 0; x < 576; x++ {
				if rows[y][x] {
					rx0, ry0 = min(rx0, x), min(ry0, y)
					rx1, ry1 = max(rx1, x), max(ry1, y)
				}
			}
		}
		for _, edge := range []struct {
			name string
			got  int
			want int
		}{{"left", rx0, sx0}, {"top", ry0, sy0}, {"right", rx1, sx1}, {"bottom", ry1, sy1}} {
			if edge.got < edge.want-1 || edge.got > edge.want+1 {
				t.Fatalf("q=%d: ink %s edge %d, want %d±1 (clipping or bleed)", q, edge.name, edge.got, edge.want)
			}
		}
		// Deterministic retry: same input bytes, same output bytes.
		out2, err := JPEGToESCPOSWithMaxWidth(wp7EncodeGrayJPEG(srcGray, q), 256, 576)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(out, out2) {
			t.Fatalf("q=%d: retry produced different bytes", q)
		}
		wp7Dump(t, "wp7_real_escpos_q"+strconv.Itoa(q)+".png", rows)
	}
}

func TestWP7QualityPDFEmbedsOriginalBytes(t *testing.T) {
	f := wp7BuildProcFixture()
	data := wp7EncodeGrayJPEG(f.aa, 95)
	g := testRasterGeometry(576)
	mm := 80.0
	dpi := 203
	g.PaperWidthMM, g.DPIX, g.DPIY = &mm, &dpi, &dpi
	pdf, err := JPEGToPDFGeometry(data, g)
	if err != nil {
		t.Fatal(err)
	}
	if got := wp7ExtractDCTStream(t, pdf); !bytes.Equal(got, data) {
		t.Fatalf("JPEGToPDFGeometry re-encoded or altered the JPEG (%d vs %d bytes)", len(got), len(data))
	}
	// Paged PDF on a short receipt (single page, no blank-break search).
	g2 := testRasterGeometry(576)
	ph, rows := 60.0, 200
	zero := 0
	g2.PaperWidthMM, g2.PaperHeightMM = &mm, &ph
	g2.PrintableHeightDots, g2.DPIX, g2.DPIY = &rows, &dpi, &dpi
	g2.OffsetXDots, g2.OffsetYDots = &zero, &zero
	short := image.NewGray(image.Rect(0, 0, 576, 150))
	for i := range short.Pix {
		short.Pix[i] = 255
	}
	shortData := wp7EncodeGrayJPEG(short, 95)
	pdf2, err := JPEGToPagedPDFGeometry(shortData, g2)
	if err != nil {
		t.Fatal(err)
	}
	if got := wp7ExtractDCTStream(t, pdf2); !bytes.Equal(got, shortData) {
		t.Fatalf("JPEGToPagedPDFGeometry re-encoded or altered the JPEG (%d vs %d bytes)", len(got), len(shortData))
	}
	wp7DumpBytes(t, "wp7_receipt.pdf", pdf)
}

func wp7ExtractDCTStream(t *testing.T, pdf []byte) []byte {
	t.Helper()
	idx := bytes.Index(pdf, []byte("/Filter /DCTDecode"))
	if idx < 0 {
		t.Fatal("PDF has no DCTDecode image stream")
	}
	lengthIdx := bytes.Index(pdf[idx:], []byte("/Length "))
	if lengthIdx < 0 {
		t.Fatal("PDF image stream has no /Length")
	}
	rest := pdf[idx+lengthIdx+len("/Length "):]
	end := bytes.IndexByte(rest, ' ')
	if end < 0 {
		t.Fatal("PDF image /Length unparsable")
	}
	n, err := strconv.Atoi(string(rest[:end]))
	if err != nil {
		t.Fatal(err)
	}
	streamIdx := bytes.Index(pdf[idx:], []byte("stream\n"))
	if streamIdx < 0 {
		t.Fatal("PDF image stream marker missing")
	}
	start := idx + streamIdx + len("stream\n")
	if start+n > len(pdf) {
		t.Fatal("PDF image stream truncated")
	}
	return pdf[start : start+n]
}

func TestWP7QualityLegacyJobsStillPrint(t *testing.T) {
	// Old-shape jobs: legacy q90 bytes, odd widths, 1-row, gray JPEG.
	for _, dims := range [][2]int{{384, 200}, {576, 900}, {851, 120}, {1700, 60}, {576, 1}} {
		w, h := dims[0], dims[1]
		var enc bytes.Buffer
		gray := image.NewGray(image.Rect(0, 0, w, h))
		for i := range gray.Pix {
			gray.Pix[i] = 255
		}
		if err := jpeg.Encode(&enc, gray, &jpeg.Options{Quality: 90}); err != nil {
			t.Fatal(err)
		}
		out, err := JPEGToESCPOSWithMaxWidth(enc.Bytes(), 256, w)
		if err != nil {
			t.Fatalf("%dx%d legacy job failed: %v", w, h, err)
		}
		_, rw, rh := wp7DecodeESCPOS(t, out)
		// Rows are byte-packed: an odd dot width pads to the next byte
		// boundary with white bits (the existing odd-width contract).
		if wantW := (w + 7) / 8 * 8; rw != wantW || rh != h {
			t.Fatalf("%dx%d legacy job became %dx%d, want %dx%d", w, h, rw, rh, wantW, h)
		}
	}
	// Oversize still fails closed (the production gate is unchanged):
	// no silent downscale of a job rendered for another printer width.
	g := testRasterGeometry(576)
	doc := Document{Kind: KindImage, Data: createTestJPEG(577, 10), GeometryFingerprint: strings.Repeat("a", 64)}
	if _, err := prepareESCPOSImage("escpos", g, doc); err == nil {
		t.Fatal("oversize image silently accepted; fail-closed gate changed")
	}
	// Job identity / queue / retry semantics untouched: the conversion
	// takes no time, randomness or job state — same bytes, same output.
	data := createTestJPEG(576, 100)
	a, err := JPEGToESCPOSWithMaxWidth(data, 256, 576)
	if err != nil {
		t.Fatal(err)
	}
	b, err := JPEGToESCPOSWithMaxWidth(data, 256, 576)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(a, b) {
		t.Fatal("identical job bytes produced different raster output")
	}
}
